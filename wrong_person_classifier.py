def classify_reply(reply_text: str, original_email: str) -> Dict[str, object]:
    text_raw = preprocess_raw(reply_text)
    text_norm = normalize(text_raw)

    all_emails = extract_emails(text_raw)
    alternate_emails = filter_alternate_emails(all_emails, original_email)

    dsn = match_score(text_norm, DSN_PATTERNS)
    if dsn.score >= 10:
        best_alt = rank_best_alternate_email(text_norm, original_email, alternate_emails)
        return {
            "reply_type": "dsn_bounce",
            "tag": "dsn_bounce",
            "subtype": None,
            "total_score": dsn.score,
            "bucket_scores": {},
            "matched_patterns": {"DSN": dsn.matched},
            "alternate_emails": alternate_emails,
            "best_alternate_email": best_alt,
            "best_alternate_name": extract_name_near_email(text_raw, best_alt) if best_alt else None,
        }

    auto = match_score(text_norm, AUTO_REPLY_PATTERNS)
    reply_type = "auto_reply" if auto.score > 0 else "human_reply"

    bucket_scores: Dict[str, int] = {}
    matched_patterns: Dict[str, List[str]] = {}
    total_score = 0

    for subtype, patterns in WP_PATTERNS.items():
        res = match_score(text_norm, patterns)
        bucket_scores[subtype] = res.score
        total_score += res.score
        if res.matched:
            matched_patterns[subtype] = res.matched

    ooo = match_score(text_norm, OOO_PATTERNS)
    if ooo.matched:
        matched_patterns["OOO"] = ooo.matched

    max_bucket = max_value(bucket_scores)
    if ooo.score > 0 and max_bucket < THRESHOLD_MAX_BUCKET:
        total_score -= OOO_PENALTY

    if max_bucket >= THRESHOLD_MAX_BUCKET:
        best_subtypes = [key for key, value in bucket_scores.items() if value == max_bucket]
        chosen = next((item for item in SUBTYPE_PRIORITY if item in best_subtypes), None)
        if not chosen:
            chosen = best_subtypes[0]

        best_alt = rank_best_alternate_email(text_norm, original_email, alternate_emails)
        return {
            "reply_type": reply_type,
            "tag": "wrong_person",
            "subtype": chosen,
            "total_score": total_score,
            "bucket_scores": bucket_scores,
            "matched_patterns": matched_patterns,
            "alternate_emails": alternate_emails,
            "best_alternate_email": best_alt,
            "best_alternate_name": extract_name_near_email(text_raw, best_alt) if best_alt else None,
        }

    best_alt = rank_best_alternate_email(text_norm, original_email, alternate_emails)
    return {
        "reply_type": reply_type,
        "tag": "not_wrong_person",
        "subtype": None,
        "total_score": total_score,
        "bucket_scores": bucket_scores,
        "matched_patterns": matched_patterns,
        "alternate_emails": alternate_emails,
        "best_alternate_email": best_alt,
        "best_alternate_name": extract_name_near_email(text_raw, best_alt) if best_alt else None,
    }


def choose_reply_text(body_text: str, body_html: str) -> str:
    text = (body_text or "").strip()
    if text:
        return text
    html = (body_html or "").strip()
    return html if html else ""


def preprocess_raw(text: str) -> str:
    value = safe_string(text)
    value = strip_html(value)
    value = strip_quoted_thread(value)
    return value.strip()


def strip_html(text: str) -> str:
    if not re.search(r"<[^>]+>", text):
        return text

    updated = re.sub(r"<\s*(script|style)[^>]*>[\s\S]*?<\s*/\s*\1\s*>", " ", text, flags=re.IGNORECASE)
    updated = re.sub(r"<br\s*/?>", "\n", updated, flags=re.IGNORECASE)
    updated = re.sub(r"</p\s*>", "\n", updated, flags=re.IGNORECASE)
    updated = re.sub(r"<[^>]+>", " ", updated)
    updated = decode_entities(updated)
    return updated


def decode_entities(text: str) -> str:
    return (
        text.replace("&nbsp;", " ")
        .replace("&amp;", "&")
        .replace("&lt;", "<")
        .replace("&gt;", ">")
        .replace("&quot;", '"')
        .replace("&#39;", "'")
    )


def strip_quoted_thread(text: str) -> str:
    lines = text.splitlines()
    kept = [line for line in lines if not line.strip().startswith(">")]
    text2 = "\n".join(kept)

    lower = text2.lower()
    separators = ["-----original message-----", "----- original message -----"]

    cut_index = -1
    for sep in separators:
        idx = lower.find(sep)
        if idx >= 0:
            cut_index = idx if cut_index == -1 else min(cut_index, idx)

    match = re.search(r"^\s*on .+ wrote:\s*$", text2, flags=re.IGNORECASE | re.MULTILINE)
    if match:
        cut_index = match.start() if cut_index == -1 else min(cut_index, match.start())

    if cut_index >= 0:
        return text2[:cut_index].strip()
    return text2.strip()


def normalize(text: str) -> str:
    return re.sub(r"\s+", " ", safe_string(text)).strip().lower()


def match_score(text_norm: str, patterns: Iterable[Pattern]) -> MatchResult:
    score = 0
    matched: List[str] = []
    for pattern in patterns:
        if pattern.regex.search(text_norm):
            score += pattern.weight
            matched.append(pattern.pattern_id)
    return MatchResult(score=score, matched=matched)


def max_value(values: Dict[str, int]) -> int:
    return max(values.values()) if values else 0


def extract_emails(text_raw: str) -> List[str]:
    found: Dict[str, bool] = {}
    text = safe_string(text_raw)

    for match in re.finditer(r"([a-z0-9._%+-]+)@([a-z0-9.-]+\.[a-z]{2,})", text, flags=re.IGNORECASE):
        email = f"{match.group(1)}@{match.group(2)}".lower()
        found[email] = True

    obfuscated = re.compile(
        r"([a-z0-9._%+-]+)\s*(?:\(|\[)?\s*(?:at|@)\s*(?:\)|\])?\s*([a-z0-9.-]+)\s*(?:\(|\[)?\s*(?:dot|\.)\s*(?:\)|\])?\s*([a-z]{2,})(?:\s*(?:\(|\[)?\s*(?:dot|\.)\s*(?:\)|\])?\s*([a-z]{2,}))?",
        flags=re.IGNORECASE,
    )
    for match in obfuscated.finditer(text):
        local = (match.group(1) or "").lower()
        domain = (match.group(2) or "").lower()
        tld1 = (match.group(3) or "").lower()
        tld2 = (match.group(4) or "").lower()
        if local and domain and tld1:
            email = f"{local}@{domain}.{tld1}.{tld2}" if tld2 else f"{local}@{domain}.{tld1}"
            found[email] = True

    return sorted(found.keys())


def filter_alternate_emails(emails: Sequence[str], original_email: str) -> List[str]:
    original = safe_string(original_email).strip().lower()
    out = []
    for email in emails:
        if not email:
            continue
        if original and email == original:
            continue
        local = email.split("@", 1)[0] if "@" in email else ""
        if re.search(r"^(no[-_]?reply|do[-_]?not[-_]?reply|donotreply|mailer-daemon|postmaster)$", local, re.IGNORECASE):
            continue
        out.append(email)
    return out


def rank_best_alternate_email(text_norm: str, original_email: str, candidates: Sequence[str]) -> Optional[str]:
    if not candidates:
        return None

    orig_domain = ""
    original = safe_string(original_email).lower()
    if "@" in original:
        orig_domain = original.split("@", 1)[1]

    cue = re.compile(r"\b(contact|reach|email|write to|forward|redirected|new email)\b", re.IGNORECASE)

    best = None
    best_score = -999

    for email in candidates:
        score = 0
        idx = text_norm.find(email)
        if idx >= 0:
            left = max(0, idx - 120)
            right = min(len(text_norm), idx + 120)
            window = text_norm[left:right]
            if cue.search(window):
                score += 3

            rx = re.compile(r"\bnew email\b[\s\S]{0,80}" + re.escape(email), re.IGNORECASE)
            if rx.search(window):
                score += 1

        if orig_domain and email.endswith("@" + orig_domain):
            score += 2

        if score > best_score:
            best_score = score
            best = email

    return best if best_score >= 3 else None


def extract_name_near_email(text_raw: str, best_email: Optional[str]) -> Optional[str]:
    if not best_email:
        return None

    raw = safe_string(text_raw)
    idx = raw.lower().find(best_email.lower())
    if idx < 0:
        return None

    start = max(0, idx - 140)
    end = min(len(raw), idx + 40)
    window = raw[start:end]

    match = re.search(
        r"\bcontact\s+([A-Z][a-z]+(?:\s+[A-Z][a-z]+){0,2})\s+(?:at|via)\s+" + re.escape(best_email),
        window,
        flags=re.IGNORECASE,
    )
    if match:
        return match.group(1).strip()

    match = re.search(
        r"([A-Z][a-z]+(?:\s+[A-Z][a-z]+){0,2})\s*\(\s*" + re.escape(best_email) + r"\s*\)",
        window,
        flags=re.IGNORECASE,
    )
    if match:
        return match.group(1).strip()

    match = re.search(
        r"([A-Z][a-z]+(?:\s+[A-Z][a-z]+){0,2})\s*[:\-]\s*" + re.escape(best_email),
        window,
        flags=re.IGNORECASE,
    )
    if match:
        return match.group(1).strip()

    return None


def safe_string(value: object) -> str:
    if value is None:
        return ""
    return str(value)


def build_output_row(result: Dict[str, object]) -> Dict[str, str]:
    return {
        "reply_type": safe_string(result.get("reply_type", "")),
        "tag": safe_string(result.get("tag", "")),
        "subtype": safe_string(result.get("subtype", "")),
        "total_score": safe_string(result.get("total_score", "")),
        "best_alternate_email": safe_string(result.get("best_alternate_email", "")),
        "best_alternate_name": safe_string(result.get("best_alternate_name", "")),
        "alternate_emails": ", ".join(result.get("alternate_emails", []) or []),
        "matched_patterns": json.dumps(result.get("matched_patterns", {}), ensure_ascii=False),
    }


def find_column_indices(fieldnames: Sequence[str], column_name: Optional[str], column_index: Optional[int]) -> Optional[int]:
    if column_index is not None:
        return column_index
    if not column_name:
        return None
    lowered = [name.strip().lower() for name in fieldnames]
    target = column_name.strip().lower()
    if target in lowered:
        return lowered.index(target)
    return None


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Classify wrong-person replies and extract alternate emails from a CSV file.",
    )
    parser.add_argument("input_csv", help="Path to input CSV with email content.")
    parser.add_argument(
        "--output",
        dest="output_csv",
        help="Path to output CSV. Defaults to <input>_classified.csv.",
    )
    parser.add_argument(
        "--body-text-col",
        default="email_body_text",
        help="Column header containing the plain-text email body.",
    )
    parser.add_argument(
        "--body-html-col",
        default="email_body_html",
        help="Column header containing the HTML email body.",
    )
    parser.add_argument(
        "--body-text-index",
        type=int,
        default=None,
        help="0-based column index for plain-text body (overrides --body-text-col).",
    )
    parser.add_argument(
        "--body-html-index",
        type=int,
        default=None,
        help="0-based column index for HTML body (overrides --body-html-col).",
    )
    parser.add_argument(
        "--original-email-col",
        default=None,
        help="Optional column header for the original recipient email.",
    )
    parser.add_argument(
        "--original-email-index",
        type=int,
        default=None,
        help="0-based column index for the original recipient email.",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    input_path = Path(args.input_csv)
    output_path = Path(args.output_csv) if args.output_csv else input_path.with_name(f"{input_path.stem}_classified.csv")

    with input_path.open("r", newline="", encoding="utf-8") as handle:
        reader = csv.DictReader(handle)
        fieldnames = reader.fieldnames or []
        if not fieldnames:
            raise ValueError("Input CSV must include a header row.")

        text_index = find_column_indices(fieldnames, args.body_text_col, args.body_text_index)
        html_index = find_column_indices(fieldnames, args.body_html_col, args.body_html_index)
        original_index = find_column_indices(fieldnames, args.original_email_col, args.original_email_index)

        if text_index is None and html_index is None:
            raise ValueError("Provide at least one email body column via --body-text-col/index or --body-html-col/index.")

        output_fieldnames = list(fieldnames) + [
            "reply_type",
            "tag",
            "subtype",
            "total_score",
            "best_alternate_email",
            "best_alternate_name",
            "alternate_emails",
            "matched_patterns",
        ]

        rows = []
        for row in reader:
            values = list(row.values())
            body_text = values[text_index] if text_index is not None and text_index < len(values) else ""
            body_html = values[html_index] if html_index is not None and html_index < len(values) else ""
            original_email = values[original_index] if original_index is not None and original_index < len(values) else ""

            reply_text = choose_reply_text(body_text, body_html)
            result = classify_reply(reply_text, original_email)
            row.update(build_output_row(result))
            rows.append(row)

    with output_path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=output_fieldnames)
        writer.writeheader()
        writer.writerows(rows)

    print(f"Wrote {len(rows)} rows to {output_path}")


if __name__ == "__main__":
    main()

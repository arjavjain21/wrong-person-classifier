#!/usr/bin/env python3
"""Wrong-person reply classifier and alternate email extractor.

This script ports the Google Apps Script classifier into a standalone,
flexible Python CLI that operates on CSV files.
"""
from __future__ import annotations

import argparse
import csv
import json
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, Iterable, List, Optional, Sequence, Tuple


THRESHOLD_MAX_BUCKET = 6
OOO_PENALTY = 8

SUBTYPE_PRIORITY = [
    "WP6_DECEASED",
    "WP5_COMPANY_CLOSED",
    "WP1_LEFT_COMPANY",
    "WP4_EMAIL_CHANGED_OR_FORWARDING",
    "WP3_NOT_MONITORED",
    "WP2_NOT_RIGHT_PERSON",
]


@dataclass(frozen=True)
class Pattern:
    pattern_id: str
    regex: re.Pattern[str]
    weight: int


@dataclass
class MatchResult:
    score: int
    matched: List[str]


def compile_patterns(items: Sequence[Tuple[str, str, int]], flags: int = re.IGNORECASE) -> List[Pattern]:
    return [Pattern(pattern_id=i, regex=re.compile(pattern, flags), weight=weight) for i, pattern, weight in items]


